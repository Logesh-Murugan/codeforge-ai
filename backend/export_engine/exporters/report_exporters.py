    ba = bundle.get_agent_output_json("business_analyst")

    lines = [
        "# ER Diagram\n",
        f"> {bundle.metadata.title} · Generated {_now()}\n\n",
    ]

    # Mermaid diagram from database engineer
    mermaid = db.get("er_diagram_mermaid", "")
    if mermaid:
        lines.append("## Entity Relationship Diagram\n")
        lines.append(_code_block(mermaid, "mermaid"))

    # Entities from business analyst
    entities = ba.get("entities", [])
    rels = ba.get("relationships", [])
    if entities and not mermaid:
        lines.append("## Entities (Mermaid ERD)\n")
        mermaid_lines = ["erDiagram"]
        for entity in entities:
            name = entity.get("name", "Entity")
            fields = entity.get("fields", [])
            mermaid_lines.append(f"  {name} {{")
            for field in fields:
                mermaid_lines.append(f"    string {field}")
            mermaid_lines.append("  }")
        for rel in rels:
            from_ = rel.get("from_", "A")
            to = rel.get("to", "B")
            rtype = rel.get("type", "has")
            mermaid_lines.append(f'  {from_} ||--o{{ {to} : "{rtype}"')
        lines.append(_code_block("\n".join(mermaid_lines), "mermaid"))

    # Entities list
    if entities:
        lines.append("## Entity List\n")
        for entity in entities:
            name = entity.get("name", "")
            fields = entity.get("fields", [])
            lines.append(f"### {name}\n")
            lines.append(_bullet_list(fields))

    return GeneratedReport(
        report_type=ReportType.ER_DIAGRAM,
        filename="ER_Diagram.md",
        content="\n".join(lines),
    )


