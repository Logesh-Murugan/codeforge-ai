def export_agent_execution(bundle: ProjectBundle) -> GeneratedReport:
    lines = [
        "# Agent Execution Report\n",
        f"> {bundle.metadata.title} · Generated {_now()}\n\n",
        "## Pipeline Summary\n",
        f"**Project:** {bundle.metadata.title}\n",
        f"**Status:** {bundle.metadata.status}\n",
        f"**Total Agents:** {len(bundle.agent_outputs)}\n\n",
    ]

    # Pipeline order
    PIPELINE_ORDER = [
        "project_manager", "business_analyst", "product_owner",
        "solution_architect", "database_engineer", "api_designer",
        "backend_developer", "security_engineer", "qa_engineer",
        "frontend_developer", "code_reviewer", "documentation_writer",
        "devops_engineer",
    ]

    completed = sum(1 for a in bundle.agent_outputs if a.status == "completed")
    failed    = sum(1 for a in bundle.agent_outputs if a.status == "failed")
    lines.append(f"**Completed:** {completed} | **Failed:** {failed}\n\n")

    # Per-agent details
    lines.append("## Agent Details\n")
    lines.append("| Agent | Status | Exec Time | Retries | Files |")
    lines.append("|-------|--------|-----------|---------|-------|")

    agent_map = {a.agent_name: a for a in bundle.agent_outputs}
    for agent_name in PIPELINE_ORDER:
        a = agent_map.get(agent_name)
        if a:
            status_icon = {"completed": "✅", "failed": "❌", "running": "⏳", "skipped": "⏭️"}.get(a.status, "❓")
            exec_time = f"{a.execution_time_seconds:.1f}s" if a.execution_time_seconds else "—"
            files = len(a.generated_files)
            lines.append(f"| {agent_name.replace('_', ' ').title()} | {status_icon} {a.status} | {exec_time} | {a.retry_count} | {files} |")
        else:
            lines.append(f"| {agent_name.replace('_', ' ').title()} | ⏭️ skipped | — | 0 | 0 |")
    lines.append("")

    # Detailed output per agent
    lines.append("## Agent Outputs\n")
    for agent_name in PIPELINE_ORDER:
        a = agent_map.get(agent_name)
        if not a:
            continue
        lines.append(f"### {agent_name.replace('_', ' ').title()}\n")
        lines.append(f"**Status:** {a.status}  ")
        if a.error_message:
            lines.append(f"**Error:** {a.error_message}\n")
        if a.output_json:
            # Show a brief summary — first 3 keys
            keys = list(a.output_json.keys())[:3]
            for k in keys:
                val = a.output_json[k]
                if isinstance(val, str):
                    lines.append(f"**{k}:** {val[:200]}\n")
                elif isinstance(val, list):
                    lines.append(f"**{k}:** {len(val)} items\n")
        lines.append("")

    return GeneratedReport(
        report_type=ReportType.AGENT_EXECUTION,
        filename="Agent_Execution_Report.md",
        content="\n".join(lines),
    )


