    if auth_flow:
        lines.append("## Authentication\n")
        lines.append(f"**Method:** {_safe(auth_flow.get('method'))}\n")
        lines.append(f"**Token Endpoint:** `{_safe(auth_flow.get('token_endpoint'))}`\n")
        lines.append(f"**Refresh Endpoint:** `{_safe(auth_flow.get('refresh_endpoint'))}`\n")
        lines.append(f"{_safe(auth_flow.get('description'))}\n\n")

    # Versioning
    lines.append(f"**Versioning Strategy:** {_safe(api.get('versioning_strategy'))}\n\n")

    # Endpoints
    endpoints = api.get("endpoints", [])
    if endpoints:
        lines.append("## Endpoints\n")
        for ep in endpoints:
            auth = " 🔒" if ep.get("auth_required") else ""
            lines.append(f"### `{ep.get('method','')} {ep.get('path','')}`{auth}\n")
            lines.append(f"{_safe(ep.get('summary'))}\n")
            if ep.get("request_model"):
                lines.append(f"**Request Model:** `{ep['request_model']}`\n")
            if ep.get("response_model"):
                lines.append(f"**Response Model:** `{ep['response_model']}`\n")
            errors = ep.get("error_responses", [])
            if errors:
                lines.append(f"**Error Responses:** {', '.join(errors)}\n")
            lines.append("")

    # Request models
    req_models = api.get("request_models", [])
    if req_models:
        lines.append("## Request Models\n")
        for m in req_models:
            lines.append(f"### `{m.get('name','')}`\n")
            fields = m.get("fields", [])
            for f in fields:
                if isinstance(f, dict):
                    lines.append(f"- `{f.get('name','')}`: {f.get('type','')} — {f.get('description','')}")
            lines.append("")

    # OpenAPI spec
    openapi = api.get("openapi_spec", "")
    if openapi:
        lines.append("## OpenAPI Specification\n")
        lines.append(_code_block(openapi[:2000], "yaml"))

    return GeneratedReport(
        report_type=ReportType.API_DOCS,
        filename="API_Documentation.md",
        content="\n".join(lines),
    )


