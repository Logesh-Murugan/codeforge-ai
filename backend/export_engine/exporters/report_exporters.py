# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _heading(text: str, level: int = 2) -> str:
    return f"{'#' * level} {text}\n"


def _bullet_list(items: List[str]) -> str:
    if not items:
        return "_None_\n"
    return "\n".join(f"- {i}" for i in items) + "\n"


def _code_block(code: str, lang: str = "") -> str:
    return f"```{lang}\n{code}\n```\n"


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _safe(val: Any, default: str = "_Not provided_") -> str:
    if val is None:
        return default
    s = str(val).strip()
    return s if s else default


