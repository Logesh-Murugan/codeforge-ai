def export_readme(bundle: ProjectBundle) -> GeneratedReport:
    """Generate project README.md from bundle."""
    meta = bundle.metadata
    pm = bundle.get_agent_output_json("project_manager")
    ba = bundle.get_agent_output_json("business_analyst")
    dev = bundle.get_agent_output_json("devops_engineer")

    lines = [
        f"# {meta.title}\n",
        f"> Generated by CodeForge AI · {_now()}\n",
        "",
        f"## Overview\n",
        f"{_safe(meta.description, pm.get('project_summary', '_No description available._'))}\n",
        "",
    ]

    # Goals
    goals = pm.get("goals", [])
    if goals:
        lines.append("## Goals\n")
        lines.append(_bullet_list(goals))
        lines.append("")

    # Tech stack
    arch = bundle.get_agent_output_json("solution_architect")
    endpoints = arch.get("endpoints", [])
    if endpoints:
        lines.append("## API Endpoints\n")
        for ep in endpoints[:8]:
            lines.append(f"- `{ep.get('method','GET')} {ep.get('path','')}` — {ep.get('description','')}")
        lines.append("")

    # Deployment
    deployment_guide = dev.get("deployment_guide", "")
    if deployment_guide:
        lines.append("## Quick Start\n")
        lines.append(deployment_guide[:800])
        lines.append("")

    # Generated files summary
    if bundle.generated_files:
        lines.append("## Generated Files\n")
        for f in bundle.generated_files[:20]:
            lines.append(f"- `{f.path}`")
        lines.append("")

    lines.append(f"---\n_Generated by CodeForge AI on {_now()}_\n")

    return GeneratedReport(
        report_type=ReportType.README,
        filename="README.md",
        content="\n".join(lines),
    )


