def export_memory_report(bundle: ProjectBundle) -> GeneratedReport:
    lines = [
        "# Memory Report\n",
        f"> {bundle.metadata.title} · Generated {_now()}\n\n",
        f"**Total Memory Records:** {len(bundle.memory_records)}\n\n",
    ]

    if bundle.memory_records:
        # Group by artifact type
        by_type: Dict[str, int] = {}
        for rec in bundle.memory_records:
            at = rec.get("metadata", {}).get("artifact_type", "unknown") if isinstance(rec.get("metadata"), dict) else "unknown"
            by_type[at] = by_type.get(at, 0) + 1

        lines.append("## Memory by Artifact Type\n\n")
        lines.append("| Artifact Type | Count |")
        lines.append("|---------------|-------|")
        for at, count in sorted(by_type.items(), key=lambda x: -x[1]):
            lines.append(f"| {at} | {count} |")
        lines.append("")

        # Sample records
        lines.append("## Sample Memory Records\n\n")
        for rec in bundle.memory_records[:5]:
            doc = rec.get("document", "")[:200]
            meta = rec.get("metadata", {})
            at = meta.get("artifact_type", "") if isinstance(meta, dict) else ""
            lines.append(f"**{at}:** {doc}...\n")
    else:
        lines.append("_No memory records found._\n\n")

    return GeneratedReport(
        report_type=ReportType.MEMORY_REPORT,
        filename="Memory_Report.md",
        content="\n".join(lines),
    )


