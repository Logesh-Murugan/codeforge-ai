def export_architecture(bundle: ProjectBundle) -> GeneratedReport:
    arch = bundle.get_agent_output_json("solution_architect")
    pm   = bundle.get_agent_output_json("project_manager")

    lines = [
        "# Architecture Report\n",
        f"> {bundle.metadata.title} · Generated {_now()}\n\n",
        "## System Overview\n",
        f"{_safe(pm.get('project_summary'))}\n\n",
        "## Scope\n",
        f"{_safe(pm.get('project_scope'))}\n\n",
    ]

    # File structure
    file_structure = arch.get("file_structure", [])
    if file_structure:
        lines.append("## Project File Structure\n")
        lines.append(_code_block("\n".join(file_structure), ""))
        lines.append("")

    # DB Schema
    db_schema = arch.get("db_schema", [])
    if db_schema:
        lines.append("## Database Schema\n")
        for table in db_schema:
            tname = table.get("table", "unknown")
            cols = table.get("columns", [])
            lines.append(f"### `{tname}`\n")
            for col in cols:
                fk = f" → {col.get('references')}" if col.get('is_fk') else ""
                lines.append(f"- `{col.get('name')}` ({col.get('type')}){fk}")
            lines.append("")

    # Endpoints summary
    endpoints = arch.get("endpoints", [])
    if endpoints:
        lines.append("## API Endpoints Summary\n")
        lines.append("| Method | Path | Auth | Description |")
        lines.append("|--------|------|------|-------------|")
        for ep in endpoints:
            auth = "✅" if ep.get("requires_auth") else "❌"
            lines.append(f"| {ep.get('method','')} | `{ep.get('path','')}` | {auth} | {ep.get('description','')} |")
        lines.append("")

    # Risks
    risks = pm.get("risks", [])
    if risks:
        lines.append("## Risks\n")
        lines.append(_bullet_list(risks))

    return GeneratedReport(
        report_type=ReportType.ARCHITECTURE,
        filename="Architecture_Report.md",
        content="\n".join(lines),
    )


